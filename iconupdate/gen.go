// identifier returns the Go identifier cmd/iconconst generates for an icon
// ("arrow-up" → "IconArrowUp").
func identifier(name string) (string, error) {
	return constgen.Identifier(prefix, name, constgen.Camel)
}

func mustIdentifier(name string) string {
	id, err := identifier(name)
	if err != nil {
		return name
	}
	return id
}

// generate returns the Go file declaring the version constant, the
// deprecated alias variables and the alias map used by Lookup. names are the
// current icons.
func (u *updater) generate(st *state, names map[string]bool) ([]byte, error) {
	idents := map[string]string{}
	for name := range names {
		id, err := identifier(name)
		if err != nil {
			return nil, err
		}
		idents[id] = name
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by %s from %s; DO NOT EDIT.\n\n", filepath.Base(u.src.Command), filepath.Base(u.o.stateFile))
	fmt.Fprintf(&buf, "package %s\n\n", u.o.pkg)
	fmt.Fprintf(&buf, "// %s is the release of %s embedded in this package.\n", u.src.VersionConst, u.src.Name)
	fmt.Fprintf(&buf, "const %s = %q\n\n", u.src.VersionConst, st.Version)
	fmt.Fprintf(&buf, "// Deprecated aliases of %d renamed icons. Like upstream, each alias is kept\n", len(st.Aliases))
	fmt.Fprintf(&buf, "// until the next major release of %s.\n", u.src.Name)
	buf.WriteString("var (\n")
	for _, a := range st.Aliases {
		switch {
		case names[a.Name]:
			return nil, fmt.Errorf("alias %q is an icon name", a.Name)
		case !names[a.Target]:
			return nil, fmt.Errorf("alias %q: target %q does not exist", a.Name, a.Target)
		}
		id, err := identifier(a.Name)
		if err != nil {
			return nil, err
		}
		if id == mustIdentifier(a.Target) {
			continue // the Go name did not change; Lookup still needs the alias
		}
		if other, dup := idents[id]; dup {
			return nil, fmt.Errorf("alias %q and %q both map to identifier %s", a.Name, other, id)
		}
		idents[id] = a.Name
		target := mustIdentifier(a.Target)

		fmt.Fprintf(&buf, "\t// %s is the former name of %s.\n\t//\n", id, target)
		fmt.Fprintf(&buf, "\t// Deprecated: %s %s renamed %q to %q, use %s. The alias is removed with %s %d.\n",
			u.src.Name, a.Since, a.Name, a.Target, target, u.src.Name, major(a.Since)+1)
		fmt.Fprintf(&buf, "\t%s = %s\n", id, target)
	}
	buf.WriteString(")\n\n")

	buf.WriteString("// aliases maps deprecated icon names to their current names.\n")
	buf.WriteString("var aliases = map[string]string{\n")
	for _, a := range st.Aliases {
		fmt.Fprintf(&buf, "\t%q: %q,\n", a.Name, a.Target)
	}
	buf.WriteString("}\n")
	return format.Source(buf.Bytes())
}

// notes is the changelog entry of one imported release.
type notes struct {
	From, To   string
	Total      int
	Diff       iconDiff
	Aliased    []alias
	Retargeted []aliasChange
	Dropped    []aliasChange
}

// maxNotes keeps release notes below GitHub's limits for pull request bodies
// (65536 characters) and release descriptions (125000 characters).
const maxNotes = 60000

var detailsBlock = regexp.MustCompile(`(?s)<details>.*?</details>\n`)

// shorten replaces the collapsible icon lists of release notes by a link to
// the changelog if the notes are too long for GitHub.
func shorten(md, changelogURL string) string {
	if len(md) <= maxNotes {
		return md
	}
	return detailsBlock.ReplaceAllLiteralString(md, "The list is in [CHANGELOG.md]("+changelogURL+").\n")
}

func (u *updater) heading(version string) string {
	return "## " + u.src.Name + " " + version + "\n"
}

// changelogSection returns the section of the given release.
func (u *updater) changelogSection(changelog, version string) (string, error) {
	head := u.heading(version)
	i := strings.Index(changelog, head)
	if i < 0 {
		return "", fmt.Errorf("no section %q in changelog", strings.TrimSpace(head))
	}
	section := changelog[i:]
	if j := strings.Index(section[len(head):], "\n## "); j >= 0 {
		section = section[:len(head)+j+1]
	}
	return strings.TrimRight(section, "\n") + "\n", nil
}

// markdown renders the notes as a changelog section.
func (u *updater) markdown(n notes) string {
	var b strings.Builder
	b.WriteString(u.heading(n.To) + "\n")
	from := n.From
	if u.src.CompareURL != nil {
		from = fmt.Sprintf("[%s to %s](%s)", n.From, n.To, u.src.CompareURL(n.From, n.To))
	} else {
		from += " to " + n.To
	}
	fmt.Fprintf(&b, "Updated from %s, %d icons in total.\n\n", from, n.Total)

	renamed := map[string]bool{}
	for _, a := range n.Aliased {
		renamed[a.Name] = true
		renamed[a.Target] = true
	}
	var removed, added []string
	for _, name := range n.Diff.Removed {
		if !renamed[name] {
			removed = append(removed, name)
		}
	}
	for _, name := range n.Diff.Added {
		if !renamed[name] {
			added = append(added, name)
		}
	}

	if breaking := len(removed) + len(n.Dropped); breaking > 0 {
		fmt.Fprintf(&b, "> [!WARNING]\n> Breaking: %d `Icon*` variables are removed, see below.\n\n", breaking)
	}

	if len(n.Aliased) > 0 {
		fmt.Fprintf(&b, "### Renamed (%d)\n\n", len(n.Aliased))
		fmt.Fprintf(&b, "The old names stay available as deprecated aliases until %s %d; `Lookup` resolves them too. "+
			"Icons marked ⚠️ look different under the new name.\n\n", u.src.Name, major(n.To)+1)
		b.WriteString("| Old name | New name | Go | Detected by |\n|---|---|---|---|\n")
		for _, a := range n.Aliased {
			mark := ""
			if n.Diff.Renames[a.Name].ShapeChanged {
				mark = " ⚠️"
			}
			fmt.Fprintf(&b, "| `%s` | `%s`%s | `%s` → `%s` | %s |\n",
				a.Name, a.Target, mark, mustIdentifier(a.Name), mustIdentifier(a.Target), u.sourceText(a.Source))
		}
		b.WriteString("\n")
	}
	if len(removed) > 0 {
		fmt.Fprintf(&b, "### Removed (%d)\n\n", len(removed))
		fmt.Fprintf(&b, "No successor was found. If there is one, add it to `aliases` in `%s` (source `manual`) and run `%s -offline`.\n\n",
			filepath.Base(u.o.stateFile), u.src.Command)
		for _, name := range removed {
			fmt.Fprintf(&b, "- `%s` (`%s`)\n", name, mustIdentifier(name))
		}
		b.WriteString("\n")
	}
	if len(n.Dropped) > 0 {
		fmt.Fprintf(&b, "### Removed deprecated aliases (%d)\n\n", len(n.Dropped))
		for _, a := range n.Dropped {
			fmt.Fprintf(&b, "- `%s` (`%s`), use `%s`: %s\n", a.Name, mustIdentifier(a.Name), mustIdentifier(a.Target), a.Note)
		}
		b.WriteString("\n")
	}
	if len(n.Retargeted) > 0 {
		fmt.Fprintf(&b, "### Updated aliases (%d)\n\n", len(n.Retargeted))
		for _, a := range n.Retargeted {
			fmt.Fprintf(&b, "- `%s`: %s\n", a.Name, a.Note)
		}
		b.WriteString("\n")
	}
	writeList(&b, "Added", added)
	writeList(&b, "Changed shape", n.Diff.Changed)
	return b.String()
}

func (u *updater) sourceText(source string) string {
	switch source {
	case sourceUpstream:
		return u.src.Name + " aliases"
	case sourceName:
		return "name"
	case sourceShape:
		return "identical shape"
	}
	return source
}

func writeList(b *strings.Builder, title string, names []string) {
	if len(names) == 0 {
		return
	}
	fmt.Fprintf(b, "### %s (%d)\n\n<details>\n<summary>Show icons</summary>\n\n", title, len(names))
	for _, name := range names {
		fmt.Fprintf(b, "- `%s` (`%s`)\n", name, mustIdentifier(name))
	}
	b.WriteString("\n</details>\n\n")
}

const changelogHeader = "# Changelog\n\n"

// prependChangelog inserts entry as the newest section of the changelog.
func prependChangelog(file, entry string) error {
	src, err := os.ReadFile(file)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	rest := strings.TrimPrefix(lf(src), changelogHeader)
	out := changelogHeader + strings.TrimRight(entry, "\n") + "\n"
	if rest = strings.TrimSpace(rest); rest != "" {
		out += "\n" + rest + "\n"
	}
	return os.WriteFile(file, []byte(out), 0o644)
}

// readmePattern matches "[Name](URL) (vX.Y.Z)".
func (u *updater) readmePattern() *regexp.Regexp {
	return regexp.MustCompile(`(\[` + regexp.QuoteMeta(u.src.Name) + `\]\(` + regexp.QuoteMeta(u.src.URL) + `\) \()v([0-9][0-9A-Za-z.+-]*)(\))`)
}

func (u *updater) readmeVersion() (string, error) {
	src, err := os.ReadFile(u.o.readme)
	if err != nil {
		return "", err
	}
	m := u.readmePattern().FindSubmatch(src)
	if m == nil {
		return "", fmt.Errorf("%s: no \"[%s](%s) (vX.Y.Z)\" found", u.o.readme, u.src.Name, u.src.URL)
	}
	return string(m[2]), nil
}

func (u *updater) updateReadme(version string) error {
	src, err := os.ReadFile(u.o.readme)
	if err != nil {
		return err
	}
	re := u.readmePattern()
	if !re.Match(src) {
		return fmt.Errorf("%s: no \"[%s](%s) (vX.Y.Z)\" found", u.o.readme, u.src.Name, u.src.URL)
	}
	out := re.ReplaceAll(src, []byte("${1}v"+version+"${3}"))
	if bytes.Equal(src, out) {
		return nil
	}
	return os.WriteFile(u.o.readme, out, 0o644)
}

// lf returns src with Windows line endings converted, as git may check out
// text files with CRLF.
func lf(src []byte) string {
	return strings.ReplaceAll(string(src), "\r\n", "\n")
}
