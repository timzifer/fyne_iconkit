package constgen

import (
	"strings"
	"testing"
	"testing/fstest"
)

func TestIdentifier(t *testing.T) {
	tests := []struct {
		prefix, name string
		c            Case
		want         string
	}{
		{"Icon", "activity", Camel, "IconActivity"},
		{"Icon", "arrow-up-left", Camel, "IconArrowUpLeft"},
		{"Icon", "123", Camel, "Icon123"},
		{"Icon", "2fa", Camel, "Icon2fa"},
		{"Icon", "brand-x_y.z", Camel, "IconBrandXYZ"},
		{"Flag", "de", Upper, "FlagDE"},
		{"Flag", "gb-eng", Upper, "FlagGB_ENG"},
		{"", "home", Camel, "Home"},
	}
	for _, tt := range tests {
		got, err := Identifier(tt.prefix, tt.name, tt.c)
		if err != nil || got != tt.want {
			t.Errorf("Identifier(%q, %q) = %q, %v; want %q", tt.prefix, tt.name, got, err, tt.want)
		}
	}

	for _, name := range []string{"123", "---"} {
		if got, err := Identifier("", name, Camel); err == nil {
			t.Errorf("Identifier(%q) = %q, want error", name, got)
		}
	}
}

func TestGenerate(t *testing.T) {
	fsys := fstest.MapFS{
		"icons/b-icon.svg": {},
		"icons/a.svg":      {},
		"icons/notes.txt":  {},
	}
	src, err := Generate(fsys, Config{Package: "fyne_test", Dir: "icons", Prefix: "Icon", Command: "iconconst -dir icons"})
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by iconconst -dir icons; DO NOT EDIT.

package fyne_test

// Names of all 2 icons in this package.
const (
	IconA     = "a"
	IconBIcon = "b-icon"
)
`
	if string(src) != want {
		t.Errorf("Generate() =\n%s\nwant\n%s", src, want)
	}
}

func TestGenerateErrors(t *testing.T) {
	tests := map[string]struct {
		fsys fstest.MapFS
		cfg  Config
		want string
	}{
		"collision":   {fstest.MapFS{"i/a-b.svg": {}, "i/a_b.svg": {}}, Config{Package: "p", Dir: "i", Prefix: "I"}, "both map to"},
		"empty dir":   {fstest.MapFS{"i/x.txt": {}}, Config{Package: "p", Dir: "i", Prefix: "I"}, "no *.svg"},
		"missing dir": {fstest.MapFS{}, Config{Package: "p", Dir: "i", Prefix: "I"}, "i"},
		"bad package": {fstest.MapFS{"i/a.svg": {}}, Config{Package: "", Dir: "i", Prefix: "I"}, "package"},
		"bad ident":   {fstest.MapFS{"i/1.svg": {}}, Config{Package: "p", Dir: "i"}, "prefix"},
	}
	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			_, err := Generate(tt.fsys, tt.cfg)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Errorf("error = %v, want containing %q", err, tt.want)
			}
		})
	}
}
